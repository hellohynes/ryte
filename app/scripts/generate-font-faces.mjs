// Rebuilds src/renderer/src/fonts/font-faces.ts from the installed Fontsource packages.
// Run: node scripts/generate-font-faces.mjs && npx eslint --fix src/renderer/src/fonts/font-faces.ts
// Only the Latin face of each family is listed; characters outside it fall back to the system font.
// Also writes resources/font-licenses.txt, the licence of every bundled font.
import { mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'

const VARIABLE = [
  'geist',
  'geist-mono',
  'google-sans',
  'google-sans-code',
  'roboto',
  'roboto-mono',
  'ibm-plex-sans',
  'dm-sans',
  'cascadia-mono',
  'reddit-sans',
  'reddit-mono',
  'merriweather',
  'raleway',
  'ubuntu-sans',
  'ubuntu-sans-mono',
  'noto-sans',
  'noto-sans-mono',
  'lora',
  'work-sans',
  'jetbrains-mono'
]
// No variable build exists for these, so each weight the interface uses is its own file.
const STATIC = [
  { pkg: 'ibm-plex-mono', family: 'IBM Plex Mono', weights: [400, 500, 600, 700] },
  { pkg: 'dm-mono', family: 'DM Mono', weights: [400, 500] }
]

let out =
  '// Generated from the installed Fontsource packages (Latin faces only); see scripts/generate-font-faces.mjs.\n' +
  '// Each face is its own asset, fetched only when its family is chosen.\n\n' +
  'export interface FontFaceSource {\n  weight: string\n  url: () => Promise<string>\n}\n\n' +
  'export const FONT_FACES: Record<string, FontFaceSource[]> = {\n'

const entry = (weight, specifier) =>
  `    {\n      weight: '${weight}',\n      url: () => import('${specifier}?url').then((m) => m.default)\n    }`

for (const pkg of VARIABLE) {
  const dir = realpathSync(`node_modules/@fontsource-variable/${pkg}`)
  const css = readFileSync(`${dir}/wght.css`, 'utf8')
  const family = /font-family: '([^']+)'/.exec(css)[1]
  const weight = /font-weight: ([0-9 ]+);/.exec(css)[1]
  const file = `${pkg}-latin-wght-normal.woff2`
  if (!readdirSync(`${dir}/files`).includes(file)) throw new Error(`missing ${file}`)
  out += `  '${family}': [\n${entry(weight, `@fontsource-variable/${pkg}/files/${file}`)}\n  ],\n`
}
for (const { pkg, family, weights } of STATIC) {
  const faces = weights.map((w) =>
    entry(String(w), `@fontsource/${pkg}/files/${pkg}-latin-${w}-normal.woff2`)
  )
  out += `  '${family}': [\n${faces.join(',\n')}\n  ],\n`
}
out += '}\n'
writeFileSync('src/renderer/src/fonts/font-faces.ts', out)

// The fonts ship inside the app, so each licence (SIL OFL for most, Ubuntu Font Licence for Ubuntu)
// ships with it too.
const packages = [
  ...VARIABLE.map((pkg) => `@fontsource-variable/${pkg}`),
  ...STATIC.map(({ pkg }) => `@fontsource/${pkg}`)
]
let notices =
  'Fonts bundled with Ryte. Generated by scripts/generate-font-faces.mjs; do not edit by hand.\n'
for (const name of packages) {
  const dir = realpathSync(`node_modules/${name}`)
  const { license } = JSON.parse(readFileSync(`${dir}/package.json`, 'utf8'))
  notices += `\n${'='.repeat(78)}\n${name} (${license})\n${'='.repeat(78)}\n\n`
  notices += `${readFileSync(`${dir}/LICENSE`, 'utf8').trim()}\n`
}
mkdirSync('resources', { recursive: true })
writeFileSync('resources/font-licenses.txt', notices)
