// Writes src/contract/manifest.generated.ts: the area, operation and event channel names of the contract,
// and nothing else. The sandboxed preload builds window.ryte from it, so it must import nothing (no Zod,
// no Node built-ins). The definitions in src/contract/ stay the single source.
// Usage: pnpm contract:generate           write the file
//        pnpm contract:generate --check   exit 1 when the committed file is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { contract } from '../src/contract'

const manifestPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/contract/manifest.generated.ts'
)

function literalObject(entries: Array<[string, string]>, indent: string): string {
  if (entries.length === 0) return '{}'
  const lines = entries.map(([key, channel]) => `${indent}  ${key}: '${channel}'`)
  return `{\n${lines.join(',\n')}\n${indent}}`
}

export function renderManifest(): string {
  const areas = Object.entries(contract).map(([name, area]) => {
    const operations = Object.entries(area.operations).map(([key, operation]): [string, string] => [
      key,
      operation.channel
    ])
    const events = Object.entries(area.events).map(([key, event]): [string, string] => [
      key,
      event.channel
    ])
    return [
      `  ${name}: {`,
      `    operations: ${literalObject(operations, '    ')},`,
      `    events: ${literalObject(events, '    ')}`,
      '  }'
    ].join('\n')
  })

  return [
    '// GENERATED by `pnpm contract:generate` from src/contract/. Do not edit by hand.',
    '// Names only: the sandboxed preload builds window.ryte from this, so it imports nothing.',
    'export const manifest = {',
    areas.join(',\n'),
    '} as const',
    ''
  ].join('\n')
}

const next = renderManifest()
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(manifestPath, 'utf8')
  } catch {
    /* a missing file is stale */
  }
  if (current !== next) {
    console.error(
      'src/contract/manifest.generated.ts is out of date. Run `pnpm contract:generate` and commit it.'
    )
    process.exitCode = 1
  }
} else {
  writeFileSync(manifestPath, next)
  console.log('Wrote src/contract/manifest.generated.ts')
}
