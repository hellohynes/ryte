// Regenerates the Stencil stylesheets from their definitions:
//   src/renderer/src/stencil/tokens.css  from tokens/scales.ts  (space, block, layout, type, border)
//   src/renderer/src/stencil/colors.css  from tokens/colors.ts  (palettes, semantic color, shadows)
//   src/renderer/src/stencil/layout.css  from components/layout-props.ts  (StStack and StBox rules)
//   src/renderer/src/stencil/text.css    from components/text-props.ts  (StText rules)
//   src/renderer/src/stencil/button.css  from components/button-props.ts  (StButton and StIconButton rules)
//   src/renderer/src/stencil/input.css   from components/input-props.ts  (StInput rules)
//   src/renderer/src/stencil/notice.css  from components/notice-props.ts  (StNotice rules)
//   ../site/stencil-tokens.css           tokens.css + colors.css for the website
// Usage: pnpm stencil:tokens           write the files
//        pnpm stencil:tokens -- --check  exit 1 when a committed file is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { renderColorsCss } from '../src/renderer/src/stencil/tokens/colors'
import { renderButtonCss } from '../src/renderer/src/stencil/tokens/render-button-css'
import { renderInputCss } from '../src/renderer/src/stencil/tokens/render-input-css'
import { renderNoticeCss } from '../src/renderer/src/stencil/tokens/render-notice-css'
import { renderLayoutCss } from '../src/renderer/src/stencil/tokens/render-layout-css'
import { renderTextCss } from '../src/renderer/src/stencil/tokens/render-text-css'
import { renderTokensCss } from '../src/renderer/src/stencil/tokens/render-css'

const stencilDir = resolve(dirname(fileURLToPath(import.meta.url)), '../src/renderer/src/stencil')
const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '../../site')
const siteTokens = `/*
 * Stencil tokens for the website: the scales, type roles, shadows, and rings the landing page reads,
 * so the site and the app share one source. GENERATED by \`pnpm stencil:tokens\` (app/). Do not edit.
 * The site is dark only; pin it with <html data-theme="dark">.
 */
`
const outputs = [
  { name: 'stencil/tokens.css', path: resolve(stencilDir, 'tokens.css'), next: renderTokensCss() },
  { name: 'stencil/colors.css', path: resolve(stencilDir, 'colors.css'), next: renderColorsCss() },
  { name: 'stencil/layout.css', path: resolve(stencilDir, 'layout.css'), next: renderLayoutCss() },
  { name: 'stencil/text.css', path: resolve(stencilDir, 'text.css'), next: renderTextCss() },
  { name: 'stencil/button.css', path: resolve(stencilDir, 'button.css'), next: renderButtonCss() },
  { name: 'stencil/input.css', path: resolve(stencilDir, 'input.css'), next: renderInputCss() },
  { name: 'stencil/notice.css', path: resolve(stencilDir, 'notice.css'), next: renderNoticeCss() },
  {
    name: 'site/stencil-tokens.css',
    path: resolve(siteDir, 'stencil-tokens.css'),
    next: `${siteTokens}${renderTokensCss()}\n${renderColorsCss()}`
  }
]

if (process.argv.includes('--check')) {
  for (const output of outputs) {
    if (readFileSync(output.path, 'utf8') !== output.next) {
      console.error(`${output.name} is out of date. Run \`pnpm stencil:tokens\`.`)
      process.exitCode = 1
    } else {
      console.log(`${output.name} is up to date.`)
    }
  }
} else {
  for (const output of outputs) {
    writeFileSync(output.path, output.next)
    console.log(`Wrote ${output.path.replace(process.cwd() + '/', '')}`)
  }
}
